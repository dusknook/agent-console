# make-bgm.py — 60.0s 零版权 BGM，纯 numpy 合成（skill 06-audio §20 路线：没有授权音乐又不能侵权时用）
#
# 设计原则：BGM 是「陪衬」不是「主角」——本片是信息图动画，人要在读字。
#   · 全片只做一个 A 小调的和声进程，靠"密度"和"低频"表达段落，不靠旋律抢注意力
#   · 每个章节的情绪跟着画面走（v2：15 章 / 60.0s）
#       01 自白      Am 铺底，稀疏 pentatonic pluck
#       02 痛点      Am9 加九度，不安；三次下行的短音
#       03 ctx 入场费 Fm 压下去 + 全片第一处 49Hz 低频（"还没开工，先花掉"）
#       04 处境      F 卡住、闷；继续下行
#       05 初心      C 被点亮；上行
#       06 答案      G→C 展开、笃定
#       07 idx 索引  Cadd→Dm7 轻快上行 + 29 格逐格点亮的上升 shimmer
#       08 不服      Am→Dm 豆包来了，半音碰撞
#       09 交锋      E 未解决，切分对抗
#       10 危机      Fm 全片最暗 + 48Hz + 0.24s 时钟滴答
#       11 立住      撕纸 → 沉默（只剩低频）→ 护栏立起来（明亮解决）
#       12 结果      Em→Am 平稳回归
#       13 bill 账单  Em 结算 + 四声"落账"音 → 省 9% → 20/20 全绿
#       14 盲区      G→D 落错分支的那一跳
#       15 命题      C→Am 抬起来 + 终止式，温暖收束
#
# 时间轴铁律：CH / sub / MEL / pulse / tick 里的每一个时刻，都必须能对回 src/scene.js 的 CHAPTERS。
# 改了 CHAPTERS 就必须重排这里，否则音画会错位（本文件与 scene.js 是同一份时间轴的两次实现）。
import numpy as np, wave, os

SR = 48000
DUR = 60.0
N = int(SR * DUR)
t = np.arange(N) / SR
L = np.zeros(N); R = np.zeros(N)

def add(l, r, at):
    """把一段信号叠到时间轴 at 秒处（越界截断，不报错）"""
    i = int(at * SR)
    if i >= N: return
    n = min(len(l), N - i)
    if n <= 0: return
    L[i:i+n] += l[:n]; R[i:i+n] += r[:n]

def pad(freqs, a, b, amp=0.040, detune=0.0022):
    """垫底和声：多个正弦 + 慢速失谐拍频 + 两端交叉淡化，段落之间无缝衔接"""
    n = int(SR * (b - a)); tt = np.arange(n) / SR
    l = np.zeros(n); r = np.zeros(n)
    for k, f in enumerate(freqs):
        ph = (k * 1.7) % 6.28
        vib = 1 + detune * np.sin(2 * np.pi * (0.13 + 0.05 * k) * tt + ph)
        s = np.sin(2 * np.pi * f * vib * tt + ph)
        # 轻微 airy 二次谐波，避免过纯的"合成器味"
        s += 0.16 * np.sin(2 * np.pi * f * 2 * vib * tt + ph * 1.9)
        pan = (k % 2) * 0.55 - 0.28
        l += s * (1 - max(0, pan)); r += s * (1 + min(0, pan))
    l *= amp; r *= amp
    # 段落间 0.7s 交叉淡化：避免和弦切换时听到"咔"
    # （段长 < 1.4s 时不做淡化 —— 那几处是刻意要的硬切入静默，见 11b）
    x = int(0.7 * SR)
    if x * 2 < n:
        l[:x] *= np.linspace(0, 1, x); l[-x:] *= np.linspace(1, 0, x)
        r[:x] *= np.linspace(0, 1, x); r[-x:] *= np.linspace(1, 0, x)
    return l, r

def pluck(f0, dur, amp, pan=0.0, decay=3.4, bright=0.35):
    """拨弦：快起音 + 指数衰减。bright 控制泛音量（越大越脆）"""
    n = int(SR * dur); tt = np.arange(n) / SR
    env = np.exp(-decay * tt) * np.minimum(1, tt * 260)
    s = np.sin(2 * np.pi * f0 * tt)
    s += bright * np.sin(2 * np.pi * f0 * 2 * tt + 0.4)
    s += bright * 0.4 * np.sin(2 * np.pi * f0 * 3 * tt + 0.9)
    s *= env * amp
    return s * (1 - max(0, pan)), s * (1 + min(0, pan))

def pulse(at, amp=0.05, f=880, dur=0.10):
    """脉冲：短促的带包络正弦，做"数据在流动"的感觉"""
    n = int(SR * dur); tt = np.arange(n) / SR
    env = np.exp(-26 * tt) * np.minimum(1, tt * 900)
    s = np.sin(2 * np.pi * f * tt) * env * amp
    return s, s

def tick(at, amp=0.035):
    """时钟滴答：极短的高频点击（危机段的倒计时）"""
    n = int(SR * 0.03); tt = np.arange(n) / SR
    env = np.exp(-90 * tt)
    s = (np.sin(2 * np.pi * 2600 * tt) + 0.6 * np.sin(2 * np.pi * 4100 * tt + 1.1)) * env * amp
    return s, s

