# ---------------------------------------------------------------- 低频：只在"有重量"的地方进入
def sub(f0, a, b, amp=0.030):
    n = int(SR * (b - a)); tt = np.arange(n) / SR
    s = np.sin(2 * np.pi * f0 * tt) * amp
    x = int(0.5 * SR)
    if x * 2 < n:
        s[:x] *= np.linspace(0, 1, x); s[-x:] *= np.linspace(1, 0, x)
    return s, s
